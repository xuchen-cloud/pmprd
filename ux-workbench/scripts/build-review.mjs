import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const result = await build({
  entryPoints: [path.join(root, 'src/review-entry.jsx')],
  bundle: true, minify: true, write: false, format: 'iife', target: ['chrome110'],
  outfile: path.join(root, 'artifacts/reader.js'),
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'inline',
});
const js = result.outputFiles.find(file => file.path.endsWith('.js'))?.text;
const css = result.outputFiles.find(file => file.path.endsWith('.css'))?.text || '';
if (!js) throw new Error('离线阅读器打包未产生 JavaScript。');
await fs.mkdir(path.join(root, 'src/generated'), { recursive: true });
await fs.writeFile(path.join(root, 'src/generated/review-runtime.mjs'),
  '// Generated by scripts/build-review.mjs.\nexport const runtimeJs = ' + JSON.stringify(js) + ';\nexport const runtimeCss = ' + JSON.stringify(css) + ';\n');
console.log(`Offline reader: ${Buffer.byteLength(js)} bytes JS, ${Buffer.byteLength(css)} bytes CSS`);
