// Rebuild only when upgrading parser dependencies. The copied skill runs without npm.
import { build } from 'esbuild';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const tooling = dirname(fileURLToPath(import.meta.url));
const output = resolve(tooling, '../scripts/vendor');
await mkdir(output, { recursive: true });
const result = await build({
  absWorkingDir: tooling,
  entryPoints: { 'static-html': 'static-html-entry.mjs', 'markdown-lexer': 'markdown-lexer-entry.mjs' },
  outdir: output,
  outExtension: { '.js': '.mjs' },
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  minify: true,
  legalComments: 'eof',
  metafile: true,
  banner: { js: '// Generated by tooling/build-vendor.mjs. See THIRD_PARTY_LICENSES.txt for licenses.' },
});
const packageDirs = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  if (match) packageDirs.add(resolve(tooling, match[1]));
}
const notices = [];
for (const packageDir of [...packageDirs].sort()) {
  const info = JSON.parse(await readFile(join(packageDir, 'package.json'), 'utf8'));
  const licenseName = (await readdir(packageDir)).find(name => /^licen[sc]e(?:\.|$)/i.test(name));
  if (!licenseName) throw new Error(`Missing bundled dependency license: ${info.name}`);
  notices.push(`${info.name}@${info.version}\n${typeof info.repository === 'string' ? info.repository : info.repository?.url || ''}\n\n${await readFile(join(packageDir, licenseName), 'utf8')}`);
}
await writeFile(join(output, 'THIRD_PARTY_LICENSES.txt'), notices.join('\n\n----------------------------------------\n\n'));
process.stdout.write(`Bundled ${packageDirs.size} dependency licenses into scripts/vendor.\n`);
